create function public.get_paginated_orders(
  p_search_term text,
  p_filters     jsonb,
  p_sort        jsonb,
  p_limit       integer,
  p_offset      integer
)
returns table (
  id                  integer,
  due_date            date,
  production_stage    text,
  priority            integer,
  customer_name       text,
  product_model_name  text,
  product_id          integer,
  product_type        text,
  total_count         bigint
)
language plpgsql stable set search_path = ''
as $$
declare
  v_sort_key       text    := coalesce(p_sort ->> 'key', 'priority');
  v_sort_dir       text    := coalesce(p_sort ->> 'direction', 'desc');
  v_stage_keys     text[]  := array(select key from jsonb_each_text(coalesce(p_filters -> 'stage', '{}'::jsonb)) where value::boolean);
  v_priority_keys  text[]  := array(select key from jsonb_each_text(coalesce(p_filters -> 'priority', '{}'::jsonb)) where value::boolean);
  v_overdue_only   boolean := coalesce((p_filters -> 'overdue' ->> 'true')::boolean, false);
  v_show_delivered boolean := 'delivered' = any (v_stage_keys);
  v_today          date    := public.business_today();
begin
  return query
  with items as (
    select
      oi.id,
      oi.due_date,
      oi.priority,
      oi.product_type,
      oi.delivery_date,
      cd.customer_name,
      coalesce(sp.model_name, bp.model_name) as product_model_name,
      coalesce(oi.sofa_product_id, oi.bed_product_id) as product_id,
      (select string_agg(s.code, ', ' order by s.sort_order)
         from public.order_item_stage_status oiss
         join public.stages s on s.stage_id = oiss.stage_id
        where oiss.order_item_id = oi.id and oiss.status = 'active') as active_codes,
      (select bool_and(oiss.status = 'completed')
         from public.order_item_stage_status oiss
        where oiss.order_item_id = oi.id) as all_completed
    from public.order_items oi
    join public.orders o            on o.id = oi.order_id
    join public.customer_details cd on cd.id = o.customer_id
    left join public.sofa_products sp on sp.id = oi.sofa_product_id
    left join public.bed_products  bp on bp.id = oi.bed_product_id
    where
      (coalesce(p_search_term, '') = ''
        or oi.id::text      ilike '%' || p_search_term || '%'
        or cd.customer_name ilike '%' || p_search_term || '%'
        or sp.model_name    ilike '%' || p_search_term || '%'
        or bp.model_name    ilike '%' || p_search_term || '%')
      and (oi.delivery_date is null or v_show_delivered)
      and (v_priority_keys = '{}' or oi.priority::text = any (v_priority_keys))
      and (not v_overdue_only or (oi.due_date < v_today and oi.delivery_date is null))
  ),
  labelled as (
    select
      i.*,
      case
        when i.delivery_date is not null then 'delivered'
        when i.active_codes is null and i.all_completed then 'out_for_delivery'
        else coalesce(i.active_codes, 'pending')
      end as stage_label
    from items i
  ),
  filtered as (
    select l.*
    from labelled l
    where v_stage_keys = '{}'
       or string_to_array(l.stage_label, ', ') && v_stage_keys
  )
  select
    f.id,
    f.due_date,
    f.stage_label,
    f.priority,
    f.customer_name,
    f.product_model_name,
    f.product_id,
    f.product_type,
    count(*) over ()
  from filtered f
  order by
    case when v_sort_key = 'priority' and v_sort_dir = 'asc'  then f.priority end asc,
    case when v_sort_key = 'priority' and v_sort_dir = 'desc' then f.priority end desc,
    case when v_sort_key = 'dueDate'  and v_sort_dir = 'asc'  then f.due_date end asc,
    case when v_sort_key = 'dueDate'  and v_sort_dir = 'desc' then f.due_date end desc,
    case when v_sort_key = 'id'       and v_sort_dir = 'asc'  then f.id end asc,
    f.id desc
  limit least(greatest(coalesce(p_limit, 10), 1), 100)
  offset greatest(coalesce(p_offset, 0), 0);
end;
$$;

