  on storage.objects for select to authenticated
  using (bucket_id = 'order-images' and (select public.is_staff()));

create policy "order-images: sales can upload"
  on storage.objects for insert to authenticated
  with check (
    bucket_id = 'order-images'
    and (storage.foldername(name))[1] in ('reference', 'measurement')
    and (select public.has_role('admin', 'manager', 'sales coordinator'))
  );

