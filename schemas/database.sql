-- Role of the signed-in user, or NULL for anonymous users and users without a profile.
create function public.current_user_role()
returns public.user_role
language sql stable security definer set search_path = ''
as $$
  select p.role from public.profiles p where p.id = auth.uid();
$$;

-- True when the signed-in user has one of the given roles. NULL-safe: returns false, never NULL.
create function public.has_role(variadic roles public.user_role[])
returns boolean
language sql stable security definer set search_path = ''
as $$
  select coalesce(public.current_user_role() = any (roles), false);
$$;

create function public.is_staff()
returns boolean
language sql stable security definer set search_path = ''
as $$
  select public.current_user_role() is not null;
$$;

create function public.assert_role(variadic roles public.user_role[])
returns void
language plpgsql stable security definer set search_path = ''
as $$
begin
  if not public.has_role(variadic roles) then
    raise exception 'You do not have permission to perform this action.' using errcode = '42501';
  end if;
end;
$$;

