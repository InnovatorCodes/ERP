  on storage.objects for update to authenticated
  using (bucket_id = 'order-images' and (select public.has_role('admin', 'manager', 'sales coordinator')))
  with check (
    bucket_id = 'order-images'
    and (storage.foldername(name))[1] in ('reference', 'measurement')
    and (select public.has_role('admin', 'manager', 'sales coordinator'))
  );

create policy "order-images: sales can delete"
  on storage.objects for delete to authenticated
  using (bucket_id = 'order-images' and (select public.has_role('admin', 'manager', 'sales coordinator')));

