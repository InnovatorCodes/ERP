-- =============================================================================
-- Vinyork ERP — complete database build
--
-- Run ONCE on a fresh Supabase project: Dashboard → SQL Editor → paste → Run.
-- The whole script runs in a single transaction, so a failure leaves nothing
-- half-built.
--
-- Security model
--   * Every table has RLS. The `anon` role can read or write nothing.
--   * Roles live in public.profiles.role and are checked by public.has_role().
--   * Writes to orders, stage status and checklist progress happen only
--     through the SECURITY DEFINER functions below, which check the
--     caller's role first.
--   * A profile (and therefore any access) is created only when an admin
--     sets `app_metadata.role` on the auth user. Self-signup grants nothing.
-- =============================================================================

