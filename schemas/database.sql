-- Creates the profile when an admin creates a user with app_metadata.role set.
-- app_metadata can only be written with the secret key, so a user can never
-- choose their own role. Users without a valid role get no profile and no access.
create function public.handle_new_user()
returns trigger
language plpgsql security definer set search_path = ''
as $$
declare
  v_role public.user_role;
begin
  begin
    v_role := (new.raw_app_meta_data ->> 'role')::public.user_role;
  exception when invalid_text_representation then
    v_role := null;
  end;

  if v_role is not null then
    insert into public.profiles (id, email, full_name, role)
    values (new.id, new.email, nullif(trim(new.raw_user_meta_data ->> 'full_name'), ''), v_role);
  end if;

  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

create function public.sync_profile_email()
returns trigger
language plpgsql security definer set search_path = ''
as $$
begin
  update public.profiles set email = new.email where id = new.id;
  return new;
end;
$$;

create trigger on_auth_user_email_changed
  after update of email on auth.users
  for each row execute function public.sync_profile_email();

-- Visitors share the demo login: stop anyone changing its email, phone or password.
create function public.protect_demo_account()
returns trigger
language plpgsql security definer set search_path = ''
as $$
begin
  if exists (select 1 from public.profiles where id = old.id and role = 'demo')
     and (new.email is distinct from old.email
          or new.phone is distinct from old.phone
          or new.encrypted_password is distinct from old.encrypted_password) then
    raise exception 'The demo account cannot be changed.';
  end if;
  return new;
end;
$$;

create trigger on_auth_user_protect_demo
  before update on auth.users
  for each row execute function public.protect_demo_account();

-- Never allow the system to end up with zero admins.
create function public.protect_last_admin()
returns trigger
language plpgsql security definer set search_path = ''
as $$
begin
  if old.role = 'admin' and (tg_op = 'DELETE' or new.role is distinct from 'admin') then
    perform 1 from public.profiles where role = 'admin' for update;
    if not exists (select 1 from public.profiles where role = 'admin' and id <> old.id) then
      raise exception 'The last admin cannot be removed or demoted.';
    end if;
  end if;
  return coalesce(new, old);
end;
$$;

create trigger profiles_protect_last_admin
  before update of role or delete on public.profiles
  for each row execute function public.protect_last_admin();

