-- Internal: creates stage rows for a new order item and the checklist for its first stages.
create function public.init_order_item_stages(p_order_item_id integer)
returns void
language plpgsql set search_path = ''
as $$
begin
  insert into public.order_item_stage_status (order_item_id, stage_id, status)
  select p_order_item_id,
         s.stage_id,
         case when exists (select 1 from public.stage_dependencies d where d.stage_id = s.stage_id)
              then 'pending'::public.stage_status
              else 'active'::public.stage_status
         end
  from public.stages s;

  insert into public.product_checklist_progress (order_item_id, check_id)
  select p_order_item_id, c.check_id
  from public.checks c
  join public.order_item_stage_status oiss
    on oiss.stage_id = c.stage_id
   and oiss.order_item_id = p_order_item_id
   and oiss.status = 'active'
  where c.is_active;
end;
$$;

create function public.submit_full_order(p_customer_id integer, p_products jsonb)
returns integer
language plpgsql security definer set search_path = ''
as $$
declare
  v_order_id     integer;
  v_item         jsonb;
  v_type         text;
  v_is_existing  boolean;
  v_is_custom    boolean;
  v_product_id   integer;
  v_item_id      integer;
  v_due_date     date;
begin
  perform public.assert_role('admin', 'manager', 'sales coordinator');

  if p_products is null or jsonb_typeof(p_products) <> 'array' or jsonb_array_length(p_products) = 0 then
    raise exception 'An order needs at least one product.';
  end if;
  if jsonb_array_length(p_products) > 50 then
    raise exception 'An order can contain at most 50 products.';
  end if;
  if not exists (select 1 from public.customer_details where id = p_customer_id) then
    raise exception 'Customer % does not exist.', p_customer_id;
  end if;

  insert into public.orders (customer_id, total_products, created_by)
  values (p_customer_id, jsonb_array_length(p_products), auth.uid())
  returning id into v_order_id;

  for v_item in select value from jsonb_array_elements(p_products)
  loop
    v_type        := v_item ->> 'product_type';
    v_is_existing := coalesce((v_item ->> 'is_existing_model')::boolean, false);
    v_is_custom   := coalesce((v_item ->> 'is_customization')::boolean, false);
    v_due_date    := (v_item ->> 'due_date')::date;
    v_product_id  := null;

    if coalesce(v_type, '') not in ('sofa', 'bed') then
      raise exception 'Invalid product type "%".', coalesce(v_type, '');
    end if;
    if v_due_date is null then
      raise exception 'Every product needs a due date.';
    end if;

    if v_is_existing and not v_is_custom then
      -- Existing catalogue model, ordered as-is.
      v_product_id := (v_item ->> (v_type || '_product_id'))::integer;
      if v_type = 'sofa' then
        update public.sofa_products set purchase_count = purchase_count + 1 where id = v_product_id;
      else
        update public.bed_products set purchase_count = purchase_count + 1 where id = v_product_id;
      end if;
      if not found then
        raise exception 'The selected % (id %) no longer exists.', v_type, v_product_id;
      end if;

    elsif v_type = 'sofa' then
      -- New or customised sofa: stored as its own product row.
      insert into public.sofa_products (
        customization, model_name, description, reference_image_url, measurement_drawing_url,
        model_family_configuration, "2_seater_length", "1_seater_length",
        recliner_mechanism_mode, recliner_mechanism_flip, wood_to_floor, headrest_mode, cup_holder,
        snack_swivel_tray, daybed_headrest_mode, daybed_position, armrest_storage, storage_side,
        foam_density_seating, foam_density_backrest, belt_details, leg_type, pvd_color, chester_option,
        armrest_panels, polish_color, polish_finish, upholstery, upholstery_color,
        total_width, total_depth, total_height, seat_width, seat_depth, seat_height,
        armrest_width, armrest_depth, purchase_count
      ) values (
        v_is_custom, v_item ->> 'model_name', v_item ->> 'description',
        v_item ->> 'reference_image_url', v_item ->> 'measurement_drawing_url',
        v_item ->> 'model_family_configuration',
        (v_item ->> '2_seater_length')::numeric, (v_item ->> '1_seater_length')::numeric,
        v_item ->> 'recliner_mechanism_mode', v_item ->> 'recliner_mechanism_flip',
        (v_item ->> 'wood_to_floor')::boolean,
        coalesce(v_item ->> 'headrest_mode', 'fixed'), v_item ->> 'cup_holder',
        coalesce((v_item ->> 'snack_swivel_tray')::boolean, false),
        v_item ->> 'daybed_headrest_mode', v_item ->> 'daybed_position',
        coalesce((v_item ->> 'armrest_storage')::boolean, false), v_item ->> 'storage_side',
        (v_item ->> 'foam_density_seating')::numeric, (v_item ->> 'foam_density_backrest')::numeric,
        v_item ->> 'belt_details', v_item ->> 'leg_type', v_item ->> 'pvd_color',
        coalesce(v_item ->> 'chester_option', 'no_chester'),
        v_item ->> 'armrest_panels', v_item ->> 'polish_color', v_item ->> 'polish_finish',
        v_item ->> 'upholstery', v_item ->> 'upholstery_color',
        (v_item ->> 'total_width')::numeric, (v_item ->> 'total_depth')::numeric, (v_item ->> 'total_height')::numeric,
        (v_item ->> 'seat_width')::numeric, (v_item ->> 'seat_depth')::numeric, (v_item ->> 'seat_height')::numeric,
        (v_item ->> 'armrest_width')::numeric, (v_item ->> 'armrest_depth')::numeric,
        1
      )
      returning id into v_product_id;

    else
      insert into public.bed_products (
        customization, model_name, description, reference_image_url, measurement_drawing_url,
        bed_size, customized_mattress_size, headboard_type, storage_option, bed_portion,
        upholstery, upholstery_color, polish_color, polish_finish,
        total_width, total_depth, total_height, purchase_count
      ) values (
        v_is_custom, v_item ->> 'model_name', v_item ->> 'description',
        v_item ->> 'reference_image_url', v_item ->> 'measurement_drawing_url',
        v_item ->> 'bed_size', v_item ->> 'customized_mattress_size', v_item ->> 'headboard_type',
        v_item ->> 'storage_option', v_item ->> 'bed_portion',
        v_item ->> 'upholstery', v_item ->> 'upholstery_color', v_item ->> 'polish_color', v_item ->> 'polish_finish',
        (v_item ->> 'total_width')::numeric, (v_item ->> 'total_depth')::numeric, (v_item ->> 'total_height')::numeric,
        1
      )
      returning id into v_product_id;
    end if;

    insert into public.order_items (order_id, product_type, sofa_product_id, bed_product_id, quantity, due_date)
    values (
      v_order_id,
      v_type,
      case when v_type = 'sofa' then v_product_id end,
      case when v_type = 'bed'  then v_product_id end,
      coalesce((v_item ->> 'quantity')::integer, 1),
      v_due_date
    )
    returning id into v_item_id;

    perform public.init_order_item_stages(v_item_id);
  end loop;

  return v_order_id;
end;
$$;

-- Records the result of one QC check. Only checks of a currently active stage can change.
create function public.set_check_status(
  p_order_item_id  integer,
  p_check_id       integer,
  p_status         text,
  p_failure_report text default null
)
returns void
language plpgsql security definer set search_path = ''
as $$
declare
  v_status public.check_status;
begin
  perform public.assert_role('admin', 'manager', 'production manager');

  v_status := p_status::public.check_status;

  if v_status = 'failed' and nullif(trim(coalesce(p_failure_report, '')), '') is null then
    raise exception 'A failure report is required when a check fails.';
  end if;

  if not exists (
    select 1
    from public.checks c
    join public.order_item_stage_status oiss
      on oiss.stage_id = c.stage_id
     and oiss.order_item_id = p_order_item_id
     and oiss.status = 'active'
    join public.order_items oi
      on oi.id = p_order_item_id
     and oi.delivery_date is null
    where c.check_id = p_check_id
  ) then
    raise exception 'This check does not belong to an active stage of order item %.', p_order_item_id;
  end if;

  insert into public.product_checklist_progress (order_item_id, check_id, status, failure_report, inspected_by, updated_at)
  values (
    p_order_item_id,
    p_check_id,
    v_status,
    case when v_status = 'failed' then trim(p_failure_report) end,
    auth.uid(),
    now()
  )
  on conflict (order_item_id, check_id) do update
    set status         = excluded.status,
        failure_report = excluded.failure_report,
        inspected_by   = excluded.inspected_by,
        updated_at     = excluded.updated_at;
end;
$$;

-- Completes an active stage and activates every stage whose dependencies are now all complete.
-- Returns false (and changes nothing) while any check of the stage is pending or failed.
create function public.advance_order_stage(p_order_item_id integer, p_current_stage_id integer)
returns boolean
language plpgsql security definer set search_path = ''
as $$
declare
  v_delivery_date date;
  v_stage_status  public.stage_status;
  v_next          record;
begin
  perform public.assert_role('admin', 'manager', 'production manager');

  select delivery_date into v_delivery_date
  from public.order_items
  where id = p_order_item_id
  for update;

  if not found then
    raise exception 'Order item % does not exist.', p_order_item_id;
  end if;
  if v_delivery_date is not null then
    raise exception 'Order item % has already been delivered.', p_order_item_id;
  end if;

  select status into v_stage_status
  from public.order_item_stage_status
  where order_item_id = p_order_item_id and stage_id = p_current_stage_id;

  if v_stage_status is distinct from 'active' then
    raise exception 'This stage is not active for order item %.', p_order_item_id;
  end if;

  if exists (
    select 1
    from public.product_checklist_progress pcp
    join public.checks c on c.check_id = pcp.check_id
    where pcp.order_item_id = p_order_item_id
      and c.stage_id = p_current_stage_id
      and pcp.status not in ('passed', 'skipped')
  ) then
    return false;
  end if;

  update public.order_item_stage_status
     set status = 'completed', completed_at = now(), completed_by = auth.uid()
   where order_item_id = p_order_item_id and stage_id = p_current_stage_id;

  for v_next in
    select d.stage_id from public.stage_dependencies d where d.depends_on_stage_id = p_current_stage_id
  loop
    if not exists (
      select 1
      from public.stage_dependencies d2
      left join public.order_item_stage_status s
        on s.order_item_id = p_order_item_id and s.stage_id = d2.depends_on_stage_id
      where d2.stage_id = v_next.stage_id
        and s.status is distinct from 'completed'
    ) then
      update public.order_item_stage_status
         set status = 'active'
       where order_item_id = p_order_item_id and stage_id = v_next.stage_id and status = 'pending';

      insert into public.product_checklist_progress (order_item_id, check_id)
      select p_order_item_id, c.check_id
      from public.checks c
      where c.stage_id = v_next.stage_id and c.is_active
      on conflict (order_item_id, check_id) do nothing;
    end if;
  end loop;

  return true;
end;
$$;

-- Marks an item delivered. All stages must be complete; history is kept.
create function public.mark_order_item_delivered(p_order_item_id integer)
returns void
language plpgsql security definer set search_path = ''
as $$
declare
  v_delivery_date date;
begin
  perform public.assert_role('admin', 'manager', 'production manager');

  select delivery_date into v_delivery_date
  from public.order_items
  where id = p_order_item_id
  for update;

  if not found then
