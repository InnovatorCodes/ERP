         or cd.email         ilike '%' || p_search_term || '%')
    and (coalesce(p_status, '') = '' or cd.customer_type::text = p_status)
    and (coalesce(p_address, '') = '' or cd.address ilike '%' || p_address || '%')
  order by cd.created_at desc, cd.id desc
  limit 500;
$$;

